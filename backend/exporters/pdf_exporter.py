"""
PDF export engine for College Timetables using ReportLab.
Produces elegant, landscape multi-page PDF documents suitable for printing and administrative publishing.
"""
from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.units import inch
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    PageBreak,
    KeepTogether,
)

from ..models import TimetableDataset, ScheduleResult


def export_timetable_to_pdf(dataset: TimetableDataset, result: ScheduleResult) -> bytes:
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=landscape(A4),
        rightMargin=24,
        leftMargin=24,
        topMargin=24,
        bottomMargin=24,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    style_title = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#1E3A8A"),
        spaceAfter=4,
    )
    style_subtitle = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#475569"),
        spaceAfter=12,
    )
    style_section = ParagraphStyle(
        "SectionHeader",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=16,
        textColor=colors.HexColor("#1E40AF"),
        spaceBefore=10,
        spaceAfter=6,
    )
    style_cell_header = ParagraphStyle(
        "CellHeader",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        alignment=1,  # Center
        textColor=colors.white,
    )
    style_cell_content = ParagraphStyle(
        "CellContent",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=7,
        leading=9,
        alignment=1,  # Center
        textColor=colors.HexColor("#0F172A"),
    )
    style_cell_lunch = ParagraphStyle(
        "CellLunch",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=7,
        leading=9,
        alignment=1,
        textColor=colors.HexColor("#92400E"),
    )

    elements = []

    # Title & Subtitle
    elements.append(Paragraph(dataset.name.upper(), style_title))
    elements.append(
        Paragraph(
            f"Official Academic Timetable Schedule — {dataset.academic_term} | Generated by Intelligent Timetable Engine | "
            f"Quality Score: <b>{result.quality_score}/100</b> | Conflicts: <b>{result.hard_conflicts_count}</b>",
            style_subtitle,
        )
    )

    # 1. Executive Analytics Summary Table
    elements.append(Paragraph("Schedule Performance & Resource Analytics", style_section))
    analytics_data = [
        [
            Paragraph("<b>Timetable Quality</b>", style_cell_content),
            Paragraph(f"<b>{result.quality_score} / 100</b>", style_cell_content),
            Paragraph("<b>Hard Conflicts</b>", style_cell_content),
            Paragraph(f"<b>{result.hard_conflicts_count} (Clash-Free)</b>", style_cell_content),
            Paragraph("<b>Solver Used</b>", style_cell_content),
            Paragraph(f"<b>{result.solver_type}</b>", style_cell_content),
        ],
        [
            Paragraph("<b>Room Utilization</b>", style_cell_content),
            Paragraph(f"{result.analytics.room_utilization_rate}%", style_cell_content),
            Paragraph("<b>Avg Capacity Fit</b>", style_cell_content),
            Paragraph(f"{result.analytics.average_capacity_efficiency}%", style_cell_content),
            Paragraph("<b>Total Sessions</b>", style_cell_content),
            Paragraph(f"{len(result.schedule)} classes", style_cell_content),
        ],
        [
            Paragraph("<b>Batch Idle Gaps</b>", style_cell_content),
            Paragraph(f"{result.analytics.batch_idle_hours_per_week} hrs/wk", style_cell_content),
            Paragraph("<b>Faculty Idle Gaps</b>", style_cell_content),
            Paragraph(f"{result.analytics.faculty_idle_hours_per_week} hrs/wk", style_cell_content),
            Paragraph("<b>Faculty Preference</b>", style_cell_content),
            Paragraph(f"{result.analytics.faculty_preference_satisfaction}% satisfied", style_cell_content),
        ],
    ]

    t_analytics = Table(analytics_data, colWidths=[120, 130, 120, 130, 120, 130])
    t_analytics.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
            ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#CBD5E1")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ])
    )
    elements.append(t_analytics)
    elements.append(Spacer(1, 14))

    # Pre-index batch grid: (batch_id, day, period) -> slot
    days = dataset.time_config.days
    slot_times = dataset.time_config.slot_times
    lunch_idx = dataset.time_config.lunch_slot_idx

    batch_grid = {}
    for slot in result.schedule:
        for p in range(slot.slot_idx, slot.slot_idx + slot.duration):
            batch_grid[(slot.batch_id, slot.day_idx, p)] = slot

    # 2. Timetable Tables for each batch
    num_slots = len(slot_times)
    first_col_w = 65
    avail_width = 792 - 48 - first_col_w  # total printable width minus margins and Day col
    slot_w = avail_width / max(1, num_slots)
    col_widths = [first_col_w] + [slot_w] * num_slots

    for b_idx, batch in enumerate(dataset.batches):
        elements.append(
            Paragraph(
                f"Batch Timetable: <b>{batch.name}</b> (Semester {batch.semester} | Enrolled: {batch.size} Students)",
                style_section,
            )
        )

        # Header row: Day, Period 1, Period 2, ...
        header_row = [Paragraph("<b>Day / Time</b>", style_cell_header)]
        for s_idx, t_str in enumerate(slot_times):
            header_row.append(Paragraph(f"<b>{t_str}</b>", style_cell_header))

        table_data = [header_row]

        # Day rows
        for d_idx, d_name in enumerate(days):
            row_cells = [Paragraph(f"<b>{d_name}</b>", style_cell_header)]

            for p_idx in range(num_slots):
                if p_idx == lunch_idx:
                    row_cells.append(Paragraph("<b>LUNCH RECESS</b>", style_cell_lunch))
                elif (batch.id, d_idx, p_idx) in batch_grid:
                    s_item = batch_grid[(batch.id, d_idx, p_idx)]
                    content = (
                        f"<b>{s_item.course_code}</b><br/>"
                        f"{s_item.course_name[:18]}<br/>"
                        f"<i>{s_item.faculty_name}</i><br/>"
                        f"<b>{s_item.room_name}</b>"
                    )
                    row_cells.append(Paragraph(content, style_cell_content))
                else:
                    row_cells.append(Paragraph("<font color='#94A3B8'>—</font>", style_cell_content))

            table_data.append(row_cells)

        b_table = Table(table_data, colWidths=col_widths)
        t_style = [
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E40AF")),
            ("BACKGROUND", (0, 1), (0, -1), colors.HexColor("#3B82F6")),
            ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#94A3B8")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]

        # Style lunch column
        if lunch_idx is not None:
            lunch_col = lunch_idx + 1
            t_style.append(("BACKGROUND", (lunch_col, 1), (lunch_col, -1), colors.HexColor("#FEF3C7")))

        b_table.setStyle(TableStyle(t_style))
        elements.append(b_table)
        elements.append(Spacer(1, 14))

        if b_idx < len(dataset.batches) - 1 and (b_idx + 1) % 2 == 0:
            elements.append(PageBreak())

    doc.build(elements)
    return buffer.getvalue()
