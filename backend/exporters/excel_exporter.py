"""
Excel export engine for College Timetables using OpenPyXL.
Generates multi-sheet formatted workbooks with color-coded batch, faculty, and room schedules.
"""
from io import BytesIO
from collections import defaultdict
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

from ..models import TimetableDataset, ScheduleResult


def export_timetable_to_excel(dataset: TimetableDataset, result: ScheduleResult) -> bytes:
    wb = openpyxl.Workbook()
    # Remove default sheet
    wb.remove(wb.active)

    days = dataset.time_config.days
    slot_times = dataset.time_config.slot_times
    lunch_idx = dataset.time_config.lunch_slot_idx

    # Common styles
    font_title = Font(name="Calibri", size=16, bold=True, color="1E3A8A")
    font_subtitle = Font(name="Calibri", size=11, italic=True, color="475569")
    font_header = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    font_bold = Font(name="Calibri", size=11, bold=True)
    font_regular = Font(name="Calibri", size=10)
    font_small = Font(name="Calibri", size=9, color="334155")

    fill_header = PatternFill(start_color="1E40AF", end_color="1E40AF", fill_type="solid")
    fill_sub_header = PatternFill(start_color="3B82F6", end_color="3B82F6", fill_type="solid")
    fill_lunch = PatternFill(start_color="FEF3C7", end_color="FEF3C7", fill_type="solid")
    fill_kpi = PatternFill(start_color="EFF6FF", end_color="EFF6FF", fill_type="solid")

    thin_border_side = Side(border_style="thin", color="CBD5E1")
    box_border = Border(left=thin_border_side, right=thin_border_side, top=thin_border_side, bottom=thin_border_side)

    # 1. Sheet: Executive Summary & Analytics
    ws_sum = wb.create_sheet(title="Executive Summary")
    ws_sum.views.sheetView[0].showGridLines = True

    ws_sum.merge_cells("A1:F1")
    ws_sum["A1"] = dataset.name.upper()
    ws_sum["A1"].font = font_title
    ws_sum["A1"].alignment = Alignment(vertical="center")

    ws_sum.merge_cells("A2:F2")
    ws_sum["A2"] = f"Master Academic Timetable Schedule — {dataset.academic_term} | Generated by Intelligent Timetable Engine"
    ws_sum["A2"].font = font_subtitle

    # KPI Summary Cards
    kpis = [
        ("Timetable Quality Score", f"{result.quality_score}/100", "Overall schedule optimality"),
        ("Hard Conflicts", f"{result.hard_conflicts_count}", "0 indicates 100% clash-free"),
        ("Solver Engine", f"{result.solver_type}", f"Time: {result.execution_time_sec}s"),
        ("Total Sessions", f"{len(result.schedule)}", f"{result.analytics.total_slots_scheduled} teaching periods"),
        ("Room Utilization Rate", f"{result.analytics.room_utilization_rate}%", "College-wide resource usage"),
        ("Avg Capacity Fit", f"{result.analytics.average_capacity_efficiency}%", "Room space utilization efficiency"),
        ("Batch Idle Gaps", f"{result.analytics.batch_idle_hours_per_week} hrs/wk", "Average student wait gaps"),
        ("Faculty Idle Gaps", f"{result.analytics.faculty_idle_hours_per_week} hrs/wk", "Average instructor free gaps"),
    ]

    r_idx = 4
    for i in range(0, len(kpis), 2):
        k1, k2 = kpis[i], kpis[i+1]
        # Left card
        ws_sum.merge_cells(start_row=r_idx, start_column=1, end_row=r_idx, end_column=2)
        ws_sum.cell(row=r_idx, column=1, value=k1[0]).font = font_bold
        ws_sum.cell(row=r_idx+1, column=1, value=k1[1]).font = Font(name="Calibri", size=14, bold=True, color="1E40AF")
        ws_sum.cell(row=r_idx+2, column=1, value=k1[2]).font = font_small

        for row in range(r_idx, r_idx+3):
            for col in range(1, 3):
                ws_sum.cell(row=row, column=col).fill = fill_kpi
                ws_sum.cell(row=row, column=col).border = box_border

        # Right card
        ws_sum.merge_cells(start_row=r_idx, start_column=4, end_row=r_idx, end_column=5)
        ws_sum.cell(row=r_idx, column=4, value=k2[0]).font = font_bold
        ws_sum.cell(row=r_idx+1, column=4, value=k2[1]).font = Font(name="Calibri", size=14, bold=True, color="1E40AF")
        ws_sum.cell(row=r_idx+2, column=4, value=k2[2]).font = font_small

        for row in range(r_idx, r_idx+3):
            for col in range(4, 6):
                ws_sum.cell(row=row, column=col).fill = fill_kpi
                ws_sum.cell(row=row, column=col).border = box_border

        r_idx += 4

    # Faculty Workload Summary Table
    r_idx += 1
    ws_sum.cell(row=r_idx, column=1, value="FACULTY WORKLOAD & SCHEDULE SUMMARY").font = font_bold
    r_idx += 1
    f_headers = ["Faculty Name", "Department", "Designation", "Weekly Hours", "Max Daily", "Idle Gaps (hrs)"]
    for c_idx, h in enumerate(f_headers, start=1):
        cell = ws_sum.cell(row=r_idx, column=c_idx, value=h)
        cell.font = font_header
        cell.fill = fill_header
        cell.border = box_border

    r_idx += 1
    for f_id, f_data in result.analytics.faculty_workloads.items():
        ws_sum.cell(row=r_idx, column=1, value=f_data["name"]).font = font_regular
        ws_sum.cell(row=r_idx, column=2, value=f_data["department"]).font = font_regular
        ws_sum.cell(row=r_idx, column=3, value=f_data["designation"]).font = font_regular
        ws_sum.cell(row=r_idx, column=4, value=f_data["total_weekly_hours"]).alignment = Alignment(horizontal="center")
        ws_sum.cell(row=r_idx, column=5, value=f_data["max_daily_hours"]).alignment = Alignment(horizontal="center")
        ws_sum.cell(row=r_idx, column=6, value=f_data["idle_gap_hours"]).alignment = Alignment(horizontal="center")
        for c in range(1, 7):
            ws_sum.cell(row=r_idx, column=c).border = box_border
        r_idx += 1

    # Auto-adjust column widths
    for col in ws_sum.columns:
        max_len = max(len(str(cell.value or '')) for cell in col)
        col_letter = get_column_letter(col[0].column)
        ws_sum.column_dimensions[col_letter].width = max(max_len + 3, 14)

    # 2. Sheet: Batch Timetables
    ws_batch = wb.create_sheet(title="Student Batches")
    ws_batch.views.sheetView[0].showGridLines = True

    # Pre-map slots: (batch_id, day, period) -> slot
    batch_grid = {}
    for slot in result.schedule:
        for p in range(slot.slot_idx, slot.slot_idx + slot.duration):
            batch_grid[(slot.batch_id, slot.day_idx, p)] = (slot, p == slot.slot_idx)

    b_row = 1
    for batch in dataset.batches:
        ws_batch.cell(row=b_row, column=1, value=f"BATCH: {batch.name.upper()} (Sem {batch.semester}, Size: {batch.size} students)").font = font_bold
        ws_batch.cell(row=b_row, column=1).fill = fill_kpi
        ws_batch.merge_cells(start_row=b_row, start_column=1, end_row=b_row, end_column=len(slot_times)+1)
        b_row += 1

        # Table Header
        ws_batch.cell(row=b_row, column=1, value="Day / Period").font = font_header
        ws_batch.cell(row=b_row, column=1).fill = fill_header
        ws_batch.cell(row=b_row, column=1).border = box_border

        for c_idx, time_label in enumerate(slot_times, start=2):
            cell = ws_batch.cell(row=b_row, column=c_idx, value=time_label)
            cell.font = font_header
            cell.fill = fill_header if (c_idx - 2) != lunch_idx else fill_lunch
            if (c_idx - 2) == lunch_idx:
                cell.font = Font(name="Calibri", size=10, bold=True, color="92400E")
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            cell.border = box_border

        b_row += 1

        # Rows per Day
        for d_idx, day_name in enumerate(days):
            day_cell = ws_batch.cell(row=b_row, column=1, value=day_name)
            day_cell.font = font_bold
            day_cell.fill = fill_sub_header
            day_cell.font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
            day_cell.alignment = Alignment(horizontal="center", vertical="center")
            day_cell.border = box_border

            for p_idx in range(len(slot_times)):
                c_col = p_idx + 2
                cell = ws_batch.cell(row=b_row, column=c_col)
                cell.border = box_border

                if p_idx == lunch_idx:
                    cell.value = "LUNCH RECESS"
                    cell.fill = fill_lunch
                    cell.font = Font(name="Calibri", size=9, bold=True, color="B45309")
                    cell.alignment = Alignment(horizontal="center", vertical="center")
                elif (batch.id, d_idx, p_idx) in batch_grid:
                    slot_item, is_start = batch_grid[(batch.id, d_idx, p_idx)]
                    cell.value = f"{slot_item.course_code}: {slot_item.course_name}\nFaculty: {slot_item.faculty_name}\nRoom: {slot_item.room_name}"
                    cell.font = font_regular
                    cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
                    # Soft tint fill
                    cell.fill = PatternFill(start_color="DBEAFE", end_color="DBEAFE", fill_type="solid")
                else:
                    cell.value = "—"
                    cell.alignment = Alignment(horizontal="center", vertical="center")
                    cell.font = Font(name="Calibri", size=9, color="94A3B8")

            ws_batch.row_dimensions[b_row].height = 45
            b_row += 1

        b_row += 2  # Spacing between batches

    ws_batch.column_dimensions["A"].width = 16
    for c_idx in range(2, len(slot_times) + 2):
        col_letter = get_column_letter(c_idx)
        ws_batch.column_dimensions[col_letter].width = 24

    # 3. Sheet: Faculty Schedules
    ws_fac = wb.create_sheet(title="Faculty Schedules")
    ws_fac.views.sheetView[0].showGridLines = True

    fac_grid = {}
    for slot in result.schedule:
        for p in range(slot.slot_idx, slot.slot_idx + slot.duration):
            fac_grid[(slot.faculty_id, slot.day_idx, p)] = (slot, p == slot.slot_idx)

    f_row = 1
    for fac in dataset.faculty:
        ws_fac.cell(row=f_row, column=1, value=f"INSTRUCTOR: {fac.name.upper()} ({fac.designation}, {fac.department})").font = font_bold
        ws_fac.cell(row=f_row, column=1).fill = fill_kpi
        ws_fac.merge_cells(start_row=f_row, start_column=1, end_row=f_row, end_column=len(slot_times)+1)
        f_row += 1

        # Header
        ws_fac.cell(row=f_row, column=1, value="Day / Period").font = font_header
        ws_fac.cell(row=f_row, column=1).fill = fill_header
        ws_fac.cell(row=f_row, column=1).border = box_border

        for c_idx, time_label in enumerate(slot_times, start=2):
            cell = ws_fac.cell(row=f_row, column=c_idx, value=time_label)
            cell.font = font_header
            cell.fill = fill_header if (c_idx - 2) != lunch_idx else fill_lunch
            if (c_idx - 2) == lunch_idx:
                cell.font = Font(name="Calibri", size=10, bold=True, color="92400E")
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            cell.border = box_border
        f_row += 1

        for d_idx, day_name in enumerate(days):
            day_cell = ws_fac.cell(row=f_row, column=1, value=day_name)
            day_cell.fill = fill_sub_header
            day_cell.font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
            day_cell.alignment = Alignment(horizontal="center", vertical="center")
            day_cell.border = box_border

            for p_idx in range(len(slot_times)):
                c_col = p_idx + 2
                cell = ws_fac.cell(row=f_row, column=c_col)
                cell.border = box_border

                if p_idx == lunch_idx:
                    cell.value = "LUNCH RECESS"
                    cell.fill = fill_lunch
                    cell.font = Font(name="Calibri", size=9, bold=True, color="B45309")
                    cell.alignment = Alignment(horizontal="center", vertical="center")
                elif (fac.id, d_idx, p_idx) in fac_grid:
                    slot_item, is_start = fac_grid[(fac.id, d_idx, p_idx)]
                    cell.value = f"{slot_item.course_code}: {slot_item.course_name}\nBatch: {slot_item.batch_name}\nRoom: {slot_item.room_name}"
                    cell.font = font_regular
                    cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
                    cell.fill = PatternFill(start_color="DCFCE7", end_color="DCFCE7", fill_type="solid")
                else:
                    cell.value = "Free / Prep"
                    cell.alignment = Alignment(horizontal="center", vertical="center")
                    cell.font = Font(name="Calibri", size=9, color="94A3B8")

            ws_fac.row_dimensions[f_row].height = 42
            f_row += 1

        f_row += 2

    ws_fac.column_dimensions["A"].width = 16
    for c_idx in range(2, len(slot_times) + 2):
        col_letter = get_column_letter(c_idx)
        ws_fac.column_dimensions[col_letter].width = 24

    # 4. Sheet: Room Occupancy & Utilization
    ws_room = wb.create_sheet(title="Room Occupancy")
    ws_room.views.sheetView[0].showGridLines = True

    room_grid = {}
    for slot in result.schedule:
        for p in range(slot.slot_idx, slot.slot_idx + slot.duration):
            room_grid[(slot.room_id, slot.day_idx, p)] = slot

    r_row = 1
    for room in dataset.rooms:
        r_stat = result.analytics.room_occupancy.get(room.id, {})
        u_pct = r_stat.get("utilization_percent", 0.0)
        ws_room.cell(row=r_row, column=1, value=f"ROOM: {room.name.upper()} ({room.room_type.value}, Cap: {room.capacity} seats | Utilization: {u_pct}%)").font = font_bold
        ws_room.cell(row=r_row, column=1).fill = fill_kpi
        ws_room.merge_cells(start_row=r_row, start_column=1, end_row=r_row, end_column=len(slot_times)+1)
        r_row += 1

        # Header
        ws_room.cell(row=r_row, column=1, value="Day / Period").font = font_header
        ws_room.cell(row=r_row, column=1).fill = fill_header
        ws_room.cell(row=r_row, column=1).border = box_border

        for c_idx, time_label in enumerate(slot_times, start=2):
            cell = ws_room.cell(row=r_row, column=c_idx, value=time_label)
            cell.font = font_header
            cell.fill = fill_header if (c_idx - 2) != lunch_idx else fill_lunch
            if (c_idx - 2) == lunch_idx:
                cell.font = Font(name="Calibri", size=10, bold=True, color="92400E")
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            cell.border = box_border
        r_row += 1

        for d_idx, day_name in enumerate(days):
            day_cell = ws_room.cell(row=r_row, column=1, value=day_name)
            day_cell.fill = fill_sub_header
            day_cell.font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
            day_cell.alignment = Alignment(horizontal="center", vertical="center")
            day_cell.border = box_border

            for p_idx in range(len(slot_times)):
                c_col = p_idx + 2
                cell = ws_room.cell(row=r_row, column=c_col)
                cell.border = box_border

                if p_idx == lunch_idx:
                    cell.value = "LUNCH RECESS"
                    cell.fill = fill_lunch
                    cell.font = Font(name="Calibri", size=9, bold=True, color="B45309")
                    cell.alignment = Alignment(horizontal="center", vertical="center")
                elif (room.id, d_idx, p_idx) in room_grid:
                    slot_item = room_grid[(room.id, d_idx, p_idx)]
                    cell.value = f"{slot_item.course_code}\nBatch: {slot_item.batch_name}\nProf: {slot_item.faculty_name}"
                    cell.font = font_regular
                    cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
                    cell.fill = PatternFill(start_color="FEF08A", end_color="FEF08A", fill_type="solid")
                else:
                    cell.value = "Available"
                    cell.alignment = Alignment(horizontal="center", vertical="center")
                    cell.font = Font(name="Calibri", size=9, color="94A3B8")

            ws_room.row_dimensions[r_row].height = 42
            r_row += 1

        r_row += 2

    ws_room.column_dimensions["A"].width = 16
    for c_idx in range(2, len(slot_times) + 2):
        col_letter = get_column_letter(c_idx)
        ws_room.column_dimensions[col_letter].width = 24

    stream = BytesIO()
    wb.save(stream)
    return stream.getvalue()
